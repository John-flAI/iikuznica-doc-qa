# -*- coding: utf-8 -*-
"""«Поболтать» или «по регламентам»: приветствие и благодарность — не запрос в службу качества.

Явные приветствия, благодарности, прощания и «кто ты» распознаём словарём, без обращения к модели.
Остальное решает модель (agent.py): разговор не по делу — короткий вежливый ответ с возвратом
к регламентам; рабочий вопрос, ответа на который нет, — письмо в службу качества как прежде.
"""
import re

ROUTE = 'smalltalk'
WORD = re.compile(r'[a-zа-яе0-9]+')
MAX_WORDS = 5          # приветствие короткое; длиннее — уже сообщение с вопросом

# слова, которые ничего не решают: «большое спасибо», «спасибо вам за ответ»
FILLERS = {'и', 'за', 'тебе', 'вам', 'вас', 'тебя', 'большое', 'большой', 'огромное', 'очень', 'заранее',
           'все', 'всем', 'ответ', 'помощь', 'помощ', 'тоже', 'еще', 'раз'}
KINDS = (
    ('greeting', {'привет', 'приветствую', 'здравствуйте', 'здравствуй', 'здрасьте', 'здорово', 'здорова',
                  'добрый', 'доброе', 'доброй', 'доброго', 'день', 'дня', 'утро', 'утра', 'вечер', 'вечера',
                  'ночи', 'времени', 'суток', 'хай', 'хелло', 'hello', 'hi', 'hey', 'салют', 'как', 'дела'}),
    ('thanks', {'спасибо', 'спс', 'пасиб', 'благодарю', 'благодарствую', 'мерси', 'thank', 'thanks',
                'ок', 'окей', 'понятно', 'понял', 'поняла', 'ясно', 'принято'}),
    ('bye', {'пока', 'до', 'свидания', 'свиданья', 'досвидания', 'всего', 'хорошего', 'прощайте', 'прощай',
             'goodbye', 'bye', 'встречи'}),
)
ABOUT = {'кто ты', 'ты кто', 'кто вы', 'вы кто', 'что ты', 'что вы', 'что ты умеешь', 'что вы умеете',
         'что ты можешь', 'что вы можете', 'что ты такое', 'ты кто такой', 'кто ты такой', 'что умеешь',
         'как тебя зовут', 'как тобой пользоваться', 'как тебя использовать', 'помощь', 'help'}

REPLIES = {
    'greeting': 'Здравствуйте! Я отвечаю на вопросы по корпоративным регламентам — текстом регламента '
                'и со ссылкой на пункт.',
    'thanks': 'Пожалуйста! Если остались вопросы по регламентам — задавайте.',
    'bye': 'До свидания! Возвращайтесь с вопросами по регламентам.',
    'about': 'Я внутренний агент компании: отвечаю на вопросы по регламентам строго их текстом и показываю '
             'пункт-источник. Если ответа в регламентах нет — не выдумываю, а готовлю запрос в службу качества.',
}
STEADY = 'Я отвечаю только по корпоративным регламентам.'       # разговор ушёл от темы — возвращаем коротко
EXAMPLE = ' Задайте вопрос по регламентам, например: «%s».'


def smalltalk_kind(text):
    """'greeting' · 'thanks' · 'bye' · 'about' — для явных форм без модели; иначе None.

    Сообщение должно целиком состоять из слов одного вида (и слов-заполнителей): «привет, как оформить
    отпуск» приветствием не считается — там есть вопрос.
    """
    words = re.findall(r'[a-zа-яе0-9]+', (text or '').lower().replace('ё', 'е'))
    if not words or len(words) > MAX_WORDS:
        return None
    if ' '.join(words) in ABOUT:
        return 'about'
    for kind, vocabulary in KINDS:
        if vocabulary & set(words) and set(words) <= vocabulary | FILLERS:
            return kind
    return None


def smalltalk_reply(kind, example=''):
    """Ответ кодом: по виду сообщения; 'steady' — когда разговор надо вернуть к теме."""
    if kind == 'steady':
        return STEADY + (EXAMPLE % example if example else '')
    return REPLIES[kind] + (EXAMPLE % example if kind in ('greeting', 'about') and example else '')
