# маркеры → вес; порядок важен при равном счёте
_MARKERS: dict[str, tuple[tuple[str, int], ...]] = {
    "счёт": (("счет на оплату", 4), ("счёт на оплату", 4), ("счет №", 3), ("счёт №", 3),
             ("всего к оплате", 4), ("к оплате", 2), ("в том числе ндс", 1), ("ндс", 1)),
    "договор": (("договор", 3), ("предмет договора", 4), ("стороны заключили", 4),
                ("обязательства сторон", 3), ("настоящему договору", 4)),
    "акт": (("акт ", 3), ("акт №", 4), ("оказанных услуг", 4), ("выполненных работ", 4),
            ("услуги оказаны", 4), ("работы выполнены", 4)),
    "письмо-запрос": (("исх. №", 3), ("просим", 3), ("просьба", 3), ("запрашиваем", 4),
                      ("направляем запрос", 4), ("сообщите, пожалуйста", 3), ("предоставить", 2)),
}

_SHRUG = ("прочее", 0.3)


def classify(text: str) -> tuple[str, float]:
    """→ (тип, уверенность 0..1). Ничего не сошлось — «прочее» с низкой уверенностью."""
    t = " " + text.lower() + " "
    best, best_score = _SHRUG
    total = 0
    for тип, markers in _MARKERS.items():
        score = sum(w for m, w in markers if m in t)
        total += score
        if score > best_score:
            best, best_score = тип, score
    if best_score == 0:
        return "прочее", 0.2
    # уверенность — доля набранных очков среди всех типов + насыщение
    return best, round(min(0.95, 0.5 + 0.5 * best_score / max(total, best_score * 2)), 2)
