# </@паспорт>
import json
from datetime import date, datetime
from pathlib import Path

_DIR = Path(__file__).parent / "data"


def _load(name: str) -> list:
    return json.loads((_DIR / name).read_text(encoding="utf-8"))


def контрагенты() -> list[dict]:
    return _load("контрагенты_демо.json")


def договоры() -> list[dict]:
    return _load("договоры_демо.json")


def _по_инн(инн: str) -> dict | None:
    return next((k for k in контрагенты() if k["ИНН"] == инн), None)


def _по_названию(название: str) -> dict | None:
    # нормализуем: без кавычек и регистра — «ООО Ромашка» == «ООО «Ромашка»»
    import re
    def norm(s: str) -> str:
        return re.sub(r"[«»\"'\s]+", "", (s or "").lower())
    target = norm(название)
    if not target:
        return None
    return next((k for k in контрагенты() if target and target in norm(k["название"])), None)


def _сумма(fields: dict) -> float | None:
    f = fields.get("Сумма") or {}
    return f.get("value_num")


def сверка(fields: dict, doc_type: str) -> list[dict]:
    """Возвращает список расхождений: [{поле, в_документе, в_реестре, важность, пояснение}]."""
    out: list[dict] = []
    инн = (fields.get("ИНН") or {}).get("value")
    название = (fields.get("Контрагент") or {}).get("value", "")

    if инн:
        в_реестре = _по_инн(инн)
        if not в_реестре:
            близкий = _по_названию(название)
            if близкий:
                out.append({"поле": "ИНН", "в_документе": инн,
                            "в_реестре": близкий["ИНН"], "важность": "высокая",
                            "пояснение": (f"Название совпадает с «{близкий['название']}» из реестра, "
                                          "но ИНН другой — вероятна опечатка или подмена контрагента.")})
            else:
                out.append({"поле": "ИНН", "в_документе": инн,
                            "в_реестре": "нет такого контрагента", "важность": "высокая",
                            "пояснение": "Контрагент отсутствует в реестре компании."})
        else:
            # ИНН найден — сверяем платёжные реквизиты (классическая ловушка — подмена р/с)
            рс = (fields.get("р/с") or {}).get("value")
            if рс and рс != в_реестре["р/с"]:
                out.append({"поле": "р/с", "в_документе": рс,
                            "в_реестре": в_реестре["р/с"], "важность": "критическая",
                            "пояснение": (f"Расчётный счёт «{в_реестре['название']}» отличается от реестра — "
                                          "возможна подмена реквизитов. Платить нельзя.")})
            бик = (fields.get("БИК") or {}).get("value")
            if бик and бик != в_реестре["БИК"]:
                out.append({"поле": "БИК", "в_документе": бик,
                            "в_реестре": в_реестре["БИК"], "важность": "высокая",
                            "пояснение": "БИК банка отличается от реестра."})
            # лимит платежа
            сумма = _сумма(fields)
            if сумма is not None and сумма > в_реестре.get("лимит_платежа", 10**12):
                out.append({"поле": "Сумма", "в_документе": сумма,
                            "в_реестре": f"лимит {в_реестре['лимит_платежа']} ₽",
                            "важность": "средняя",
                            "пояснение": "Сумма превышает лимит платежа по контрагенту."})

    # срок оплаты истёк?
    срок = (fields.get("Срок оплаты") or {}).get("value")
    if срок:
        try:
            д = datetime.strptime(срок, "%d.%m.%Y").date()
            if д < date.today():
                out.append({"поле": "Срок оплаты", "в_документе": срок,
                            "в_реестре": f"сегодня {date.today().strftime('%d.%m.%Y')}",
                            "важность": "средняя",
                            "пояснение": "Срок оплаты уже истёк — риск пени."})
        except ValueError:
            pass

    # договоры: известен номер — сверяем сумму и срок действия
    номер = (fields.get("Номер") or {}).get("value")
    if номер:
        дог = next((d for d in договоры() if d["номер"] == номер), None)
        if дог:
            сумма = _сумма(fields)
            if сумма is not None and сумма > дог["сумма"]:
                out.append({"поле": "Сумма", "в_документе": сумма,
                            "в_реестре": f"{дог['сумма']} ₽ по договору {номер}",
                            "важность": "высокая",
                            "пояснение": "Сумма документа превышает сумму договора."})
    return out


def договор_по_номеру(номер: str) -> dict | None:
    return next((d for d in договоры() if d["номер"] == номер), None)
