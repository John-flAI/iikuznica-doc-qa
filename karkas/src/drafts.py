from . import registry


def _цитата_стр(filename: str, prov: dict) -> str:
    return f"«{filename}», стр. {prov['страница']}: „{prov['цитата']}“"


def _цитаты_полей(fields: dict, names: list[str], filename: str) -> list[str]:
    out = []
    for n in names:
        f = fields.get(n)
        if f:
            out.append(_цитата_стр(filename, f))
    return out


def compose(doc_type: str, fields: dict, mismatches: list[dict],
            filename: str, наш_текст: str | None = None) -> dict:
    """→ {text, citations, escalate_recommended}. наш_текст — сырой текст письма-запроса."""
    f = fields
    имя = (f.get("Контрагент") or {}).get("value", "контрагент")
    номер = (f.get("Номер") or {}).get("value", "б/н")
    сумма = (f.get("Сумма") or {}).get("value")
    срок = (f.get("Срок оплаты") or {}).get("value")
    crit = [m for m in mismatches if m["важность"] in ("критическая", "высокая")]

    text, cites, escalate = "", [], False

    if doc_type == "счёт":
        if crit:
            bad = "; ".join(f"{m['поле']}: в документе {m['в_документе']}, в реестре {m['в_реестре']}"
                            for m in crit)
            text = (f"⚠ НЕ платить без проверки. Счёт №{номер} от {имя} на {сумма or '—'} "
                    f"содержит расхождения с реестром ({bad}). "
                    "Проект ответа поставщику: «Просим подтвердить реквизиты официальным письмом — "
                    "данные в счёте не совпадают с нашим реестром». Платёж заблокирован до ответа.")
            escalate = True
        else:
            text = (f"Счёт №{номер} от {имя} на {сумма or '—'} сверён с реестром — "
                    f"реквизиты совпадают. Готовим оплату"
                    + (f" до {срок}" if срок else "") + ". Проект ответа: "
                    "«Счёт получен, принят в оплату, платёж — в ближайший платёжный день».")
        cites = _цитаты_полей(f, ["Контрагент", "ИНН", "р/с", "Сумма", "Срок оплаты"], filename)

    elif doc_type == "договор":
        escalate = True  # договоры — всегда через человека (юрист/руководитель)
        text = (f"Договор №{номер} от {имя} получен и разобран"
                + (f" (сумма {сумма})" if сумма else "") + ". "
                + ("Найдены расхождения с реестром — см. карточку. " if crit else "")
                + "Проект письма: «Документ получен, передан на проверку руководителю; "
                "по итогам проверки направим протокол разногласий либо подписанный экземпляр».")

    elif doc_type == "акт":
        text = (f"Акт №{номер} от {имя}" + (f" на {сумма}" if сумма else "") + " разобран. "
                "Проект письма: «Акт получен, сверен с документами по сделке, готовим подпись».")
        cites = _цитаты_полей(f, ["Контрагент", "Номер", "Сумма"], filename)

    elif doc_type == "письмо-запрос":
        # что мы МОЖЕМ подтвердить из реестра — и честно говорим, чего не знаем
        дог = registry.договор_по_номеру(номер) if номер != "б/н" else None
        известен = дог or next((d for d in registry.договоры()
                                if d["контрагент_ИНН"] == (f.get("ИНН") or {}).get("value")), None)
        части = [f"Проект ответа для {имя}:"]
        if известен:
            части.append(f"«подтверждаем: договор №{известен['номер']} ({известен['предмет']}) "
                         f"действует до {известен['действует_до']}, сумма по договору {известен['сумма']} ₽»")
            cites.append(f"реестр договоров: №{известен['номер']}")
        else:
            части.append("«по вашему запросу данных в нашей базе нет» — отвечаем честно, "
                         "без выдуманных реквизитов и обещаний.")
        части.append("Всё, чего нет в базе (сертификаты, акты прошлых периодов и т.п.), "
                     "агент помечает как «нет данных» и передаёт человеку.")
        escalate = True  # запросы, требующие живого ответа, уходит человеку на согласование
        text = " ".join(части)
        cites += _цитаты_полей(f, ["Контрагент", "Номер"], filename)
        if наш_текст:
            cites.append(f"«{filename}», текст запроса: „{' '.join(наш_текст.split())[:120]}…“")

    else:  # прочее
        text = ("Деловых реквизитов и запросов не найдено — похоже, это не входящий документ "
                "к исполнению. Помечаю «в архив», человеку не беспокою.")

    # одинаковые строки-источники (два поля с одной строки документа) — без дублей
    return {"text": text, "citations": list(dict.fromkeys(cites)),
            "escalate_recommended": escalate}
