def render(filename: str, lines: list[tuple[str, str]], font: str) -> None:
    c = canvas.Canvas(str(OUT / filename), pagesize=A4)
    w, h = A4
    y = h - 60
    for style, text in lines:
        size = {"title": 13, "big": 11, "norm": 10, "small": 9}[style]
        c.setFont(font, size)
        if style == "title":
            c.drawCentredString(w / 2, y, text)
            c.line(50, y - 6, w - 50, y - 6)
        else:
            c.drawString(50, y, text)
        y -= size + 9
    c.save()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    pdfmetrics.registerFont(TTFont("Font", find_font()))
    for filename, lines in DOCS:
        render(filename, lines, "Font")
    print(f"OK: {len(DOCS)} PDF в {OUT}")


if __name__ == "__main__":
    main()
