def find_font() -> str:
    import importlib.util
    for p in _FONT_CANDIDATES:
        if Path(p).exists():
            return p
    if importlib.util.find_spec("matplotlib"):  # DejaVuSans едет с matplotlib
        import matplotlib
        p = Path(matplotlib.get_data_path()) / "fonts" / "ttf" / "DejaVuSans.ttf"
        if p.exists():
            return str(p)
    sys.exit("Не найден TTF с кириллицей — положи путь в _FONT_CANDIDATES")


